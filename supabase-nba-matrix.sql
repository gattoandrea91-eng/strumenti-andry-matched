create table if not exists public.nba_matrix_bets (
 id bigint generated by default as identity primary key,
 chat_id text not null,
 message_id bigint not null,
 match text not null,
 selection text not null,
 odds numeric(9,3) not null check (odds > 1),
 probability numeric(6,5),
 result text not null default 'PENDING' check (result in ('PENDING','WIN','LOSS','VOID')),
 created_at timestamptz not null default now(),
 unique(chat_id,message_id)
);
create index if not exists nba_matrix_date on public.nba_matrix_bets(created_at);
alter table public.nba_matrix_bets enable row level security;
-- No public policies. Read/write only through server-side service key.
